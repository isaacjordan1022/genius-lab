// Hand-authored pilot content. The second form changes evidence and tasks, not just option order.
// Keys, explanations and exemplars stay on the server until grading/feedback is allowed.
type ChoiceSeed = [
  objective: string,
  prompt: string,
  correct: string,
  a: string,
  b: string,
  c: string,
  explanation: string,
];
const choice = ([
  objective,
  prompt,
  correct,
  a,
  b,
  c,
  explanation,
]: ChoiceSeed): Question => ({
  id: "",
  kind: "choice",
  objective,
  prompt,
  correct,
  choices: [a, correct, b, c],
  explanation,
  points: 4,
});
const match = (
  objective: string,
  prompt: string,
  pairs: [string, string][],
): Question => ({
  id: "",
  kind: "match",
  objective,
  prompt,
  matches: pairs.map(([left, right]) => ({ left, right })),
  explanation:
    "Compare each relationship carefully. Each correct pair earns one point.",
  points: 4,
});
const open = (
  objective: string,
  prompt: string,
  rubric: string[],
  exemplar: string,
): Question => ({
  id: "",
  kind: "open",
  objective,
  prompt,
  rubric,
  exemplar,
  explanation:
    "Different answers can earn full credit. Each fulfilled rubric criterion earns one point; explain your thinking.",
  points: 4,
});
function forms(chunk: string, a: Question[], b: Question[]): Question[][] {
  return [a, b].map((questions, formIndex) =>
    questions.map((question, index) => {
      // Deterministic option rotation prevents "always pick the second answer" without changing keys.
      const offset = (index + formIndex) % 4;
      return {
        ...question,
        id: `${chunk}-${formIndex + 1}-${index + 1}`,
        ...(question.choices
          ? {
              choices: [
                ...question.choices.slice(offset),
                ...question.choices.slice(0, offset),
              ],
            }
          : {}),
      };
    }),
  );
}

